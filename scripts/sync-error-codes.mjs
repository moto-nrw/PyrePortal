#!/usr/bin/env node
// Generates src/services/errorCodes.generated.ts from project-phoenix's
// error-registry/ domain fragments, the API error-code source (phoenix ADR 0006).
//
//   node scripts/sync-error-codes.mjs [path/to/error-registry/]
//   node scripts/sync-error-codes.mjs --check [path]   # fail if the file is stale
//
// Defaults prefer the sibling error-registry/ directory. Explicit legacy JSON
// inputs remain supported during producer rollout and for historical fixtures.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as prettier from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(root, 'src', 'services', 'errorCodes.generated.ts');
const codePattern = /^[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$/;
const errorClasses = ['input', 'permission', 'business_rejection', 'unavailable', 'server'];

export function generate(registry) {
  if (!Array.isArray(registry?.codes)) throw new Error('registry.codes must be an array');
  const entries = [...registry.codes];
  const codes = new Set();
  for (const entry of entries) {
    if (!entry || !codePattern.test(entry.code))
      throw new Error(`invalid error code: ${entry?.code}`);
    if (codes.has(entry.code)) throw new Error(`duplicate error code: ${entry.code}`);
    if (!errorClasses.includes(entry.class)) {
      throw new Error(`invalid class for ${entry.code}: ${entry.class}`);
    }
    codes.add(entry.code);
  }
  entries.sort((a, b) => a.code.localeCompare(b.code, 'en'));
  const seenLegacy = new Set();
  for (const entry of entries) {
    if (entry.legacy === undefined) continue;
    if (typeof entry.legacy !== 'string' || !entry.legacy) {
      throw new Error(`invalid legacy code for ${entry.code}`);
    }
    if (seenLegacy.has(entry.legacy)) throw new Error(`duplicate legacy code: ${entry.legacy}`);
    seenLegacy.add(entry.legacy);
  }
  const legacy = entries.filter(entry => entry.legacy && entry.legacy !== entry.code);
  for (const entry of legacy) {
    if (codes.has(entry.legacy)) {
      throw new Error(`legacy code ${entry.legacy} is also a current code; mapping is ambiguous`);
    }
  }
  const q = value => JSON.stringify(value);
  return `// Code generated by scripts/sync-error-codes.mjs from project-phoenix
// API error registry; DO NOT EDIT. Run \`pnpm run sync:error-codes\` to update.

export const ERROR_CODES = [
${entries.map(entry => `  ${q(entry.code)},`).join('\n')}
] as const;

export type ErrorCode = (typeof ERROR_CODES)[number];

export type ErrorClass = ${errorClasses.map(q).join(' | ')};

export const ERROR_CODE_CLASSES: Readonly<Record<ErrorCode, ErrorClass>> = {
${entries.map(entry => `  ${q(entry.code)}: ${q(entry.class)},`).join('\n')}
};

/**
 * Wire codes Phoenix sends until its one-time rename (project-phoenix #2506),
 * mapped to their registry code. Codes whose name does not change are absent.
 */
export const LEGACY_ERROR_CODES: Readonly<Record<string, ErrorCode>> = {
${legacy.map(entry => `  ${q(entry.legacy)}: ${q(entry.code)},`).join('\n')}
};
`;
}

/** Discover every domain, then validate one combined registry during generation. */
export function readRegistry(path) {
  let names;
  try {
    names = readdirSync(path);
  } catch (error) {
    // Dispatch using the operation itself, not a stale filesystem precheck.
    // Only a non-directory can be a historical aggregate. Missing/unreadable
    // sources must fail, never become a reason to choose another registry.
    if (error.code !== 'ENOTDIR') throw error;
    return JSON.parse(readFileSync(path, 'utf8'));
  }
  const files = names.filter(file => file.endsWith('.json')).sort();
  if (files.length === 0) throw new Error(`${path}: no error registry fragments`);
  const codes = [];
  for (const file of files) {
    if (!/^[a-z][a-z0-9_]*\.json$/.test(file))
      throw new Error(`invalid registry fragment: ${file}`);
    const fragment = JSON.parse(readFileSync(join(path, file), 'utf8'));
    if (!Array.isArray(fragment?.codes) || fragment.codes.length === 0) {
      throw new Error(`${file}: codes must be a nonempty array`);
    }
    for (const entry of fragment.codes) {
      if (typeof entry?.code !== 'string' || entry.code.split('.')[0] !== file.slice(0, -5)) {
        throw new Error(`${file}: wrong domain for ${entry?.code}`);
      }
    }
    codes.push(...fragment.codes);
  }
  return { codes };
}

function siblingRegistry(checkout) {
  const producer = join(checkout, '..', 'project-phoenix');
  let names;
  try {
    names = readdirSync(producer);
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
  // Discovery does not assert a source's type or readability. The direct read
  // remains authoritative, including when a selected source changes/disappears.
  if (names.includes('error-registry')) return join(producer, 'error-registry');
  return names.includes('error-registry.json') ? join(producer, 'error-registry.json') : null;
}

export function defaultRegistryPath(checkout = root) {
  const sibling = siblingRegistry(checkout);
  if (sibling) return sibling;
  // Managed worktrees are not siblings of the producer. Git's common directory
  // identifies this repository's main checkout without machine-specific paths.
  const common = execFileSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], {
    cwd: checkout,
    encoding: 'utf8',
  }).trim();
  return (
    siblingRegistry(dirname(common)) ?? join(checkout, '..', 'project-phoenix', 'error-registry')
  );
}

export async function renderRegistry(registry) {
  const options = await prettier.resolveConfig(outputPath);
  return prettier.format(generate(registry), { ...options, filepath: outputPath });
}

async function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const positional = args.filter(arg => arg !== '--check');
  if (positional.length > 1 || positional.some(arg => arg.startsWith('-'))) {
    throw new Error('Usage: sync-error-codes.mjs [--check] [registry-directory-or-legacy-json]');
  }
  const registryPath = resolve(positional[0] ?? defaultRegistryPath());
  const output = await renderRegistry(readRegistry(registryPath));
  if (check) {
    let current = '';
    try {
      current = readFileSync(outputPath, 'utf8');
    } catch {
      // Missing file counts as stale.
    }
    if (current !== output) {
      console.error(
        `${outputPath} is out of date with ${registryPath}. Run pnpm run sync:error-codes.`
      );
      process.exitCode = 1;
    }
  } else writeFileSync(outputPath, output);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
